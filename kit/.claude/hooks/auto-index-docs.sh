#!/usr/bin/env bash
set -euo pipefail

root="${CLAUDE_PROJECT_DIR:-$(pwd)}"
docs="$root/docs"
index="$docs/index.md"

[ -d "$docs" ] || exit 0

generate() {
  echo "# Docs index"
  echo
  echo "Generated by .claude/hooks/auto-index-docs.sh. Do not edit by hand."
  echo

  local groups
  groups=$(cd "$docs" && find . -mindepth 2 -name '*.md' -not -name README.md \
    | sed 's#^\./##' | cut -d/ -f1 | sort -u)

  local top
  top=$(cd "$docs" && find . -maxdepth 1 -name '*.md' -not -name 'index.md' -not -name README.md \
    | sed 's#^\./##' | sort)

  if [ -n "$top" ]; then
    echo "## Root"
    echo
    for f in $top; do
      echo "- [${f%.md}]($f)"
    done
    echo
  fi

  for g in $groups; do
    echo "## $g"
    echo
    (cd "$docs" && find "$g" -name '*.md' -not -name README.md | sort) | while read -r f; do
      name=$(basename "$f" .md)
      echo "- [$name]($f)"
    done
    echo
  done
}

new=$(generate)

if [ -f "$index" ] && [ "$new" = "$(cat "$index")" ]; then
  exit 0
fi

printf '%s\n' "$new" > "$index"
